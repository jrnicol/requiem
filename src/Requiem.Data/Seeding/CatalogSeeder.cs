using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;
using Requiem.Data.Entities;
using Requiem.Shared.Rules;

namespace Requiem.Data.Seeding;

public sealed record CatalogSeedData(
    IReadOnlyList<Bloodline> Bloodlines,
    IReadOnlyList<PredatorType> PredatorTypes,
    IReadOnlyList<MeritDefinition> Merits,
    IReadOnlyList<CompelDefinition> Compels,
    IReadOnlyList<EdgeDefinition> Edges,
    IReadOnlyList<PowerGroupSeed> PowerGroups,
    IReadOnlyList<PowerSeed> Powers,
    IReadOnlyList<ConceptDefinition> Concepts);

/// <summary>A power group as written in disciplines.json; <see cref="Bloodline"/> is a catalog name.</summary>
public sealed record PowerGroupSeed(
    string Name, PowerGroupKind Kind, string? Bloodline = null, string? Description = null, int? SourcePage = null);

/// <summary>
/// A power as written in powers.json (generated by tools/CatalogImport). <see cref="Group"/> and
/// <see cref="DicePoolDiscipline"/> are power group names.
/// </summary>
public sealed record PowerSeed
{
    public required string Group { get; init; }
    public int? Level { get; init; }
    public required string Name { get; init; }
    public string? Category { get; init; }
    public string? Flavor { get; init; }
    public int? VitaeCost { get; init; }
    public int? WillpowerCost { get; init; }
    public string? CostText { get; init; }
    public string? DicePoolText { get; init; }
    public CharacterAttribute? DicePoolAttribute { get; init; }
    public Skill? DicePoolSkill { get; init; }
    public string? DicePoolDiscipline { get; init; }
    public string? OpposedBy { get; init; }
    public string? ActionText { get; init; }
    public string? Duration { get; init; }
    public string? CastingDuration { get; init; }
    public string? HowToLearn { get; init; }
    public string? DramaticFailureText { get; init; }
    public string? FailureText { get; init; }
    public string? SuccessText { get; init; }
    public string? ExceptionalSuccessText { get; init; }
    public string? Notes { get; init; }
    public int? SourcePage { get; init; }
    public List<PowerBonusSeed>? BonusOptions { get; init; }
}

public sealed record PowerBonusSeed(int SuccessCost, string Effect);

public sealed record CatalogSeedResult(int Bloodlines, int PredatorTypes, int Merits, int Compels, int Edges, int PowerGroups, int Powers = 0, int Concepts = 0)
{
    public int Total => Bloodlines + PredatorTypes + Merits + Compels + Edges + PowerGroups + Powers + Concepts;
}

/// <summary>
/// Seeds the rulebook catalog from the JSON files embedded under Seed/.
/// Insert-only: entries are matched by their natural key and existing rows are never changed,
/// so the GM's edits survive re-seeding and the seeder is safe to run on every startup.
/// </summary>
public static class CatalogSeeder
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
        Converters = { new JsonStringEnumConverter(allowIntegerValues: false) },
    };

    /// <summary>Reads and validates the embedded seed files without touching a database.</summary>
    public static CatalogSeedData Load()
    {
        var data = new CatalogSeedData(
            Read<Bloodline>("bloodlines.json"),
            Read<PredatorType>("predator-types.json"),
            Read<MeritDefinition>("merits.json"),
            Read<CompelDefinition>("compels.json"),
            Read<EdgeDefinition>("edges.json"),
            Read<PowerGroupSeed>("disciplines.json"),
            Read<PowerSeed>("powers.json"),
            Read<ConceptDefinition>("concepts.json"));

        EnsureUnique(data.Bloodlines, b => b.Name, "bloodlines.json");
        EnsureUnique(data.PredatorTypes, p => p.Name, "predator-types.json");
        EnsureUnique(data.Merits, m => (m.Name, m.Kind, m.Source), "merits.json");
        EnsureUnique(data.Compels, c => c.Name, "compels.json");
        EnsureUnique(data.Compels.Where(c => c.Roll is not null), c => c.Roll, "compels.json (roll)");
        EnsureUnique(data.Edges, e => e.Name, "edges.json");
        EnsureUnique(data.Concepts, c => c.Name, "concepts.json");
        EnsureUnique(data.PowerGroups, g => g.Name, "disciplines.json");

        var unknown = data.PowerGroups.Where(g => g.Bloodline is not null && data.Bloodlines.All(b => b.Name != g.Bloodline))
            .Select(g => $"{g.Name} → {g.Bloodline}").ToList();
        if (unknown.Count > 0)
            throw new InvalidOperationException($"disciplines.json names unknown Bloodlines: {string.Join(", ", unknown)}");

        EnsureUnique(data.Powers, p => (p.Group, p.Name), "powers.json");
        var groups = data.PowerGroups.Select(g => g.Name).ToHashSet();
        var badPowers = data.Powers
            .Where(p => !groups.Contains(p.Group)
                        || p.DicePoolDiscipline is { } d && !groups.Contains(d)
                        || p.Level is < 1 or > 5
                        || p.BonusOptions?.Any(b => b.SuccessCost < 1) == true)
            .Select(p => $"{p.Group}/{p.Name}").ToList();
        if (badPowers.Count > 0)
            throw new InvalidOperationException($"powers.json has invalid entries: {string.Join(", ", badPowers)}");
        return data;
    }

    public static async Task<CatalogSeedResult> SeedAsync(RequiemDbContext db, CancellationToken cancellationToken = default)
    {
        var data = Load();
        var bloodlines = await AddMissingAsync(db.Bloodlines, data.Bloodlines, b => b.Name, cancellationToken);
        var predators = await AddMissingAsync(db.PredatorTypes, data.PredatorTypes, p => p.Name, cancellationToken);
        var merits = await AddMissingAsync(db.MeritDefinitions, data.Merits, m => (m.Name, m.Kind, m.Source), cancellationToken);
        var compels = await AddMissingAsync(db.CompelDefinitions, data.Compels, c => c.Name, cancellationToken);
        var edges = await AddMissingAsync(db.EdgeDefinitions, data.Edges, e => e.Name, cancellationToken);
        var concepts = await AddMissingAsync(db.ConceptDefinitions, data.Concepts, c => c.Name, cancellationToken);
        // Power groups link to Bloodlines by id, so those must exist first.
        if (bloodlines + predators + merits + compels + edges + concepts > 0) await db.SaveChangesAsync(cancellationToken);

        var bloodlineIds = await db.Bloodlines.AsNoTracking().ToDictionaryAsync(b => b.Name, b => b.Id, cancellationToken);
        var powerGroups = await AddMissingAsync(db.PowerGroups, data.PowerGroups.Select(g => new PowerGroup
        {
            Name = g.Name,
            Kind = g.Kind,
            // A Bloodline the GM renamed or removed just leaves the group unlinked.
            BloodlineId = g.Bloodline is not null && bloodlineIds.TryGetValue(g.Bloodline, out var id) ? id : null,
            Description = g.Description,
            SourcePage = g.SourcePage,
        }).ToList(), g => g.Name, cancellationToken);
        if (powerGroups > 0) await db.SaveChangesAsync(cancellationToken);

        var groupIds = await db.PowerGroups.AsNoTracking().ToDictionaryAsync(g => g.Name, g => g.Id, cancellationToken);
        var powers = await AddMissingAsync(db.Powers, data.Powers
            // A group the GM renamed or removed skips its powers rather than failing startup.
            .Where(p => groupIds.ContainsKey(p.Group))
            .Select(p => ToEntity(p, groupIds)).ToList(), p => (p.PowerGroupId, p.Name), cancellationToken);
        if (powers > 0) await db.SaveChangesAsync(cancellationToken);

        return new CatalogSeedResult(bloodlines, predators, merits, compels, edges, powerGroups, powers, concepts);
    }

    private static Power ToEntity(PowerSeed p, IReadOnlyDictionary<string, int> groupIds) => new()
    {
        PowerGroupId = groupIds[p.Group],
        Level = p.Level,
        Name = p.Name,
        Category = p.Category,
        Flavor = p.Flavor,
        VitaeCost = p.VitaeCost,
        WillpowerCost = p.WillpowerCost,
        CostText = p.CostText,
        DicePoolText = p.DicePoolText,
        DicePoolAttribute = p.DicePoolAttribute,
        DicePoolSkill = p.DicePoolSkill,
        DicePoolPowerGroupId = p.DicePoolDiscipline is { } d && groupIds.TryGetValue(d, out var id) ? id : null,
        OpposedBy = p.OpposedBy,
        ActionText = p.ActionText,
        Duration = p.Duration,
        CastingDuration = p.CastingDuration,
        HowToLearn = p.HowToLearn,
        DramaticFailureText = p.DramaticFailureText,
        FailureText = p.FailureText,
        SuccessText = p.SuccessText,
        ExceptionalSuccessText = p.ExceptionalSuccessText,
        Notes = p.Notes,
        SourcePage = p.SourcePage,
        IsReviewed = false,
        BonusOptions = p.BonusOptions?.Select((b, i) => new PowerBonusOption { SuccessCost = b.SuccessCost, Effect = b.Effect, SortOrder = i }).ToList() ?? [],
    };

    private static async Task<int> AddMissingAsync<T, TKey>(
        DbSet<T> set, IReadOnlyList<T> seed, Func<T, TKey> key, CancellationToken cancellationToken)
        where T : class
    {
        // Catalog tables are small; comparing in memory keeps composite keys simple.
        var existing = (await set.AsNoTracking().ToListAsync(cancellationToken)).Select(key).ToHashSet();
        var missing = seed.Where(item => !existing.Contains(key(item))).ToList();
        set.AddRange(missing);
        return missing.Count;
    }

    private static List<T> Read<T>(string fileName)
    {
        var resource = $"Seed/{fileName}";
        using var stream = typeof(CatalogSeeder).Assembly.GetManifestResourceStream(resource)
            ?? throw new InvalidOperationException($"Embedded seed file '{resource}' not found.");
        try
        {
            return JsonSerializer.Deserialize<List<T>>(stream, JsonOptions)
                ?? throw new InvalidOperationException($"Seed file '{fileName}' is empty.");
        }
        catch (JsonException ex)
        {
            throw new InvalidOperationException($"Seed file '{fileName}' is invalid: {ex.Message}", ex);
        }
    }

    private static void EnsureUnique<T, TKey>(IEnumerable<T> items, Func<T, TKey> key, string file)
    {
        var duplicates = items.GroupBy(key).Where(g => g.Count() > 1).Select(g => g.Key).ToList();
        if (duplicates.Count > 0)
            throw new InvalidOperationException($"Duplicate entries in {file}: {string.Join(", ", duplicates)}");
    }
}
